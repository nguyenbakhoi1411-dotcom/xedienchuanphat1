ALTER TABLE sales_order_items ADD COLUMN IF NOT EXISTS price_policy_code VARCHAR(60);
ALTER TABLE sales_order_items ADD COLUMN IF NOT EXISTS price_policy_name VARCHAR(160);
ALTER TABLE sales_order_items ADD COLUMN IF NOT EXISTS policy_discount_amount NUMERIC(14, 2) DEFAULT 0;

CREATE INDEX IF NOT EXISTS idx_price_policies_effective ON price_policies(status, start_date, end_date, priority, created_at);
CREATE INDEX IF NOT EXISTS idx_price_policy_targets_policy ON price_policy_targets(price_policy_id);
CREATE INDEX IF NOT EXISTS idx_product_price_history_product ON product_price_history(product_id, changed_at);
CREATE INDEX IF NOT EXISTS idx_sales_order_items_policy ON sales_order_items(price_policy_id);

