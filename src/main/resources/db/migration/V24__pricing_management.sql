CREATE TABLE IF NOT EXISTS price_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_code VARCHAR(60) NOT NULL UNIQUE,
    policy_name VARCHAR(160) NOT NULL,
    description VARCHAR(1000),
    scope_type VARCHAR(30) NOT NULL,
    price_change_type VARCHAR(30) NOT NULL,
    value NUMERIC(14, 2) NOT NULL DEFAULT 0,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    priority INTEGER NOT NULL DEFAULT 0,
    created_by VARCHAR(120) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    approved_by VARCHAR(120),
    approved_at TIMESTAMP WITH TIME ZONE,
    cancelled_by VARCHAR(120),
    cancelled_at TIMESTAMP WITH TIME ZONE,
    note VARCHAR(1000)
);

CREATE TABLE IF NOT EXISTS price_policy_targets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_policy_id BIGINT NOT NULL REFERENCES price_policies(id),
    branch_id BIGINT,
    product_id BIGINT,
    category_id BIGINT,
    brand_id BIGINT,
    category_code VARCHAR(60),
    brand VARCHAR(80)
);

CREATE TABLE IF NOT EXISTS product_price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    old_base_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    new_base_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    old_selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    new_selling_price NUMERIC(14, 2) NOT NULL DEFAULT 0,
    reason VARCHAR(500),
    source_type VARCHAR(30) NOT NULL,
    source_id BIGINT,
    changed_by VARCHAR(120) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    branch_id BIGINT,
    note VARCHAR(1000)
);

ALTER TABLE sales_order_items ADD COLUMN IF NOT EXISTS list_price NUMERIC(14, 2);
